@dataclass(frozen=True)
class CanonicalTables:
    """The resolved canonical input a lab computes over, plus its identity.

    ``tables`` records which tables were requested; it becomes part of the
    ``input_dataset_id`` so two labs reading different slices are distinguishable.
    """

    identity: ManifestIdentity
    tables: tuple[str, ...] = ()
    stories: list[dict] = field(default_factory=list)
    reviews: list[dict] = field(default_factory=list)
    analysis: list[dict] = field(default_factory=list)
    findings: list[dict] = field(default_factory=list)

    @property
    def input_dataset_id(self) -> str:
        """Stable id of the input slice, e.g. ``canonical_registry/story+review``."""
        return (
            f"canonical_registry/{'+'.join(self.tables)}" if self.tables else "canonical_registry"
        )

    @property
    def is_empty(self) -> bool:
        """True when nothing resolved — the caller should say so rather than publish zeros."""
        return not (self.stories or self.reviews or self.analysis or self.findings)

    def stories_by_id(self) -> dict[str, dict]:
        """``story_id -> payload`` for join-style labs."""
        return {str(s.get("story_id") or ""): s for s in self.stories if s.get("story_id")}

    def rows(self, table: str) -> list[dict]:
        """Rows of one table by its *table name* (``"story"``, ``"finding"``, …).

        Saves every caller from re-deriving the name→attribute mapping
        (``"story" -> .stories``, ``"analysis" -> .analysis``), which is the kind of
        duplicated lookup that silently rots when a table is added.
        """
        attr = TABLE_ATTRIBUTES.get(table)
        if attr is None:
            raise ValueError(f"unknown canonical table {table!r}; known: {list(TABLE_ATTRIBUTES)}")
        return getattr(self, attr)


def load_canonical_tables(
    *tables: str,
    manifest_path: Path | None = None,
) -> CanonicalTables:
    """Resolve the requested canonical tables. **The only input door a lab may use.**

    ::

        tables = load_canonical_tables("story")            # story labs
        tables = load_canonical_tables("story", "review")  # join labs

    Unknown table names raise immediately — a typo must not silently yield an empty table
    that then publishes as "no effect measured".
    """
    requested = tuple(tables) or ("story",)
    unknown = [t for t in requested if t not in _RESOLVERS]
    if unknown:
        raise ValueError(f"unknown canonical table(s) {unknown}; known: {list(_RESOLVERS)}")

    manifest = read_manifest(manifest_path)
    identity = manifest_identity(manifest)
    resolved = {name: _RESOLVERS[name](manifest) for name in requested}

    return CanonicalTables(
        identity=identity,
        tables=requested,
        stories=resolved.get("story", []),
        reviews=resolved.get("review", []),
        analysis=resolved.get("analysis", []),
        findings=resolved.get("finding", []),
    )
