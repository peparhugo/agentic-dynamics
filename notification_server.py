"""Notification server with a pluggable transport layer.

The server routes notification messages (broadcast, direct, channel, system)
between connected clients, persists relayed messages, and optionally uses a
Redis pub/sub backbone for cross-instance delivery.

Transport layer
---------------
The wire-level mechanics of accepting client connections and delivering
messages to them are abstracted behind the :class:`BaseTransport` interface.
The core :class:`NotificationServer` logic (message routing, channel
subscriptions, persistence, Redis backbone) is transport-agnostic and only
communicates with clients through the transport. Concrete transports provide
the actual connection handling:

* :class:`WebSocketTransport` — the default, backed by the ``websockets``
  library. It accepts WebSocket connections and serves the REST endpoints
  (``/health``, ``/channels``, ``/messages``) on the same port.

Additional transports (SSE, polling, raw TCP, ...) can be added by subclassing
:class:`BaseTransport` and registering them in ``TRANSPORT_REGISTRY``. The
active transport is selected with the ``TRANSPORT`` env var (defaulting to
``websocket``) or by passing a ``transport`` argument to
:class:`NotificationServer`.

Wire protocol
-------------
Every frame sent over the wire is base64-encoded. The payload of a frame is
the JSON serialization of a message with the following shape::

    {
        "type": "broadcast" | "direct" | "system" | "subscribe" | "unsubscribe",
        "payload": {...},
        "timestamp": "<ISO-8601 UTC string>",
    }

* ``system`` messages are generated by the server (e.g. connection handshake).
* ``broadcast`` messages sent by a client are relayed to every connected client,
  unless they carry a ``channel`` field, in which case they are relayed only to
  clients subscribed to that channel.
* ``direct`` messages carry a ``payload["to"]`` target client ID and are
  relayed only to that client.
* ``subscribe`` / ``unsubscribe`` messages carry a channel name (in ``payload``
  or as a top-level ``channel`` field) and add/remove the sender from that
  channel's subscriber list.

Channels
--------
* Clients can subscribe to any number of named channels and can
  subscribe/unsubscribe dynamically.
* A ``channel`` field (top-level or inside ``payload``) on a message restricts
  delivery to the subscribers of that channel.

Redis backbone
--------------
When a Redis broker is configured (``REDIS_URL`` env var or ``redis_client``),
the server publishes messages to Redis pub/sub channels and a background worker
subscribes to Redis and delivers messages to locally connected clients. This
lets multiple server instances share one Redis backbone. Client connection
state (connected clients and their channel subscriptions) is mirrored into
Redis so it survives a server restart.

Persistence
-----------
All relayed messages are stored in a SQLite database (``DATABASE_URL`` env var,
defaulting to ``messages.db``) and are exposed via ``GET /messages``.
"""

